#!/usr/bin/env python3
"""Acquire a pinned AI4Culture baseline, separate from the 17-family dataset.

Only images declared CC0/Public Domain Mark in upstream per-image metadata
enter candidate/. These declarations still require source/label review before
commercial training. CC BY images stay out pending complete attribution review.
No crops, augmentation, training, or random image splits are performed here.
Requires Python 3.11+ and authenticated gh for download; no chat credentials.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import shutil
import subprocess
import tarfile
from collections import Counter, defaultdict
from pathlib import Path

REVISION = "767169b2b053485ee7b909fd19b96e98f6be0453"
REPO = "datable-be/AI4_C_datasets"
ARTIFACTS = {
    "metadata.json": ("color_detection_dataset/AI4C_Textile_Pattern_Dataset_2024-06-01_0.json", "38ee91a032c67feae5b68b2b909b401a54e759d95a21bcc089aa34db972f59b8"),
    "pt1.tar.gz": ("textile_pattern_dataset/pt1.tar.gz", "d2020f7e22d774e234701a0d195dc86974234527eb9e82c2c0d78d0c6340681e"),
    "pt2.tar.gz": ("textile_pattern_dataset/pt2.tar.gz", "19e91eeda7fa720b0f8f525fad27e5f24e188c6d54173134bb6fc12ae9552b0d"),
}
LABELS = {
    "checkered pattern": "CHECKED", "dots pattern": "DOTTED",
    "floral/plant pattern": "FLORAL", "geometric pattern": "GEOMETRIC",
    "plaid pattern": "PLAID", "striped pattern": "STRIPED",
}
ALLOWED = {
    "http://creativecommons.org/publicdomain/zero/1.0/",
    "http://creativecommons.org/publicdomain/mark/1.0/",
}


def sha256(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def acquire(root: Path, offline: bool) -> None:
    root.mkdir(parents=True, exist_ok=True)
    for name, (source, expected) in ARTIFACTS.items():
        path = root / name
        if not path.exists():
            if offline:
                raise FileNotFoundError(path)
            temporary = root / (name + ".part")
            try:
                with temporary.open("wb") as out:
                    subprocess.run(["gh", "api", f"repos/{REPO}/contents/{source}?ref={REVISION}",
                                    "-H", "Accept: application/vnd.github.raw+json"], stdout=out, check=True)
                if sha256(temporary) != expected:
                    raise ValueError(f"Checksum mismatch: {name}")
                temporary.replace(path)
            finally:
                temporary.unlink(missing_ok=True)
        if sha256(path) != expected:
            raise ValueError(f"Checksum mismatch: {name}; refusing import")


def index_images(archives):
    """Index regular jpg members without extracting archive paths or symlinks."""
    result = {}
    for archive in archives:
        for member in archive.getmembers():
            if not member.isfile() or not member.name.lower().endswith(".jpg"):
                continue
            if member.size > 20 * 1024 * 1024:
                raise ValueError("Oversized image")
            name = Path(member.name).name
            if name in result:
                raise ValueError(f"Duplicate archive filename: {name}")
            result[name] = (archive, member)
    return result


def audit(root: Path) -> dict:
    data = json.loads((root / "metadata.json").read_text())
    licenses = {x["id"]: x["name"] for x in data["licenses"]}
    categories = {x["id"]: LABELS[x["name"]] for x in data["categories"]}
    annotations = defaultdict(list)
    for row in data["annotations"]:
        annotations[row["image_id"]].append(categories[row["category_id"]])
    candidate = root / "candidate"
    # Output is exclusively generated by this importer; remove stale candidate files.
    if candidate.exists():
        if candidate.is_symlink():
            raise ValueError("Candidate directory must not be a symlink")
        shutil.rmtree(candidate)
    candidate.mkdir()
    rights, counts, excluded, rows = Counter(), Counter(), Counter(), []
    hashes = defaultdict(list)
    archives = [tarfile.open(root / name, "r:gz") for name in ("pt1.tar.gz", "pt2.tar.gz")]
    try:
        images = index_images(archives)
        for image in data["images"]:
            license_url = licenses.get(image.get("license"), "missing")
            rights[license_url] += 1
            labels = annotations[image["id"]]
            label = labels[0] if len(labels) == 1 else ""
            reason = ""
            if license_url not in ALLOWED:
                reason = "rights_review"
            elif not image.get("landing_page"):
                reason = "missing_provenance"
            elif len(labels) != 1:
                reason = "ambiguous_annotation"
            elif image["file_name"] not in images:
                reason = "missing_image"
            row = {
                "image_id": image["id"], "file_name": image["file_name"], "label": label,
                "license_url": license_url, "source": image.get("source") or "",
                "landing_page": image.get("landing_page") or "", "metadata_url": image.get("url") or "",
                "status": reason or "candidate_pending_source_and_label_review",
                "path": "", "sha256": "", "group_id": "",
            }
            if reason:
                excluded[reason] += 1
            else:
                archive, member = images[image["file_name"]]
                destination = candidate / label / (image["id"] + ".jpg")
                destination.parent.mkdir(parents=True, exist_ok=True)
                with archive.extractfile(member) as src, destination.open("wb") as dst:
                    shutil.copyfileobj(src, dst)
                digest = sha256(destination)
                hashes[digest].append(image["id"])
                # Same source object must stay in one split. Near-duplicate designs
                # across distinct source objects still need manual/perceptual grouping.
                group = hashlib.sha256(row["landing_page"].encode()).hexdigest()
                row.update(path=str(destination.relative_to(root)), sha256=digest, group_id=group)
                counts[label] += 1
            rows.append(row)
    finally:
        for archive in archives:
            archive.close()
    metadata_eligible = sum(counts.values())
    rows_by_id = {row["image_id"]: row for row in rows}
    for ids in hashes.values():
        kept = rows_by_id[ids[0]]
        for image_id in ids[1:]:
            duplicate = rows_by_id[image_id]
            (root / duplicate["path"]).unlink()
            counts[duplicate["label"]] -= 1
            excluded["exact_duplicate"] += 1
            duplicate.update(status="exact_duplicate", path="", group_id=kept["group_id"])
    with (root / "manifest.csv").open("w", newline="") as out:
        writer = csv.DictWriter(out, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    report = {
        "repository": REPO, "revision": REVISION,
        "checksums": {name: checksum for name, (_, checksum) in ARTIFACTS.items()},
        "total_images": len(data["images"]), "archive_images": len(images),
        "rights_counts": dict(sorted(rights.items())), "candidate_counts": dict(sorted(counts.items())),
        "metadata_eligible_before_dedup": metadata_eligible,
        "candidate_total": sum(counts.values()), "excluded_counts": dict(excluded),
        "exact_duplicate_groups": [ids for ids in hashes.values() if len(ids) > 1],
        "unique_candidate_source_objects": len({r["group_id"] for r in rows if r["group_id"]}),
        "status": "Downloaded and metadata-filtered; NOT trained or production-approved",
        "review_required": ["Verify upstream source rights and labels", "Perceptual/design deduplication",
                            "Group splits by source object AND repeated cloth design", "Ghanaian phone-photo evaluation",
                            "No SOLID, UNKNOWN, KENTE, ANKARA, ADINKRA or material labels in this dataset"],
    }
    (root / "audit.json").write_text(json.dumps(report, indent=2) + "\n")
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, default=Path(__file__).resolve().parents[3] / ".datasets/ai4culture")
    parser.add_argument("--offline", action="store_true", help="Audit cached, checksum-verified files only")
    args = parser.parse_args()
    acquire(args.cache, args.offline)
    print(json.dumps(audit(args.cache), indent=2))


if __name__ == "__main__":
    main()
